CREATE TABLE listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    seller_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(60) NOT NULL CHECK (CHAR_LENGTH(TRIM(title)) > 0),
    price NUMERIC(12, 0) NOT NULL CHECK (price >= 1),
    condition_grade INTEGER NOT NULL CHECK (condition_grade BETWEEN 1 AND 5),
    description VARCHAR(2000) NOT NULL CHECK (CHAR_LENGTH(TRIM(description)) > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'RESERVED', 'SOLD', 'CANCELLED')),
    content_version BIGINT NOT NULL DEFAULT 0 CHECK (content_version >= 0),
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- 삭제된 초안에 대한 응답 유실 재시도를 같은 게시 결과로 돌려준다. FK는 두지 않는다.
    source_draft_id BIGINT NOT NULL UNIQUE CHECK (source_draft_id > 0),
    source_draft_version BIGINT NOT NULL CHECK (source_draft_version >= 0),
    -- PostgreSQL/H2 공통으로 열린 판매글 하나를 보장하는 부분 고유 제약의 보조 값.
    active_slot SMALLINT,
    CONSTRAINT uk_listings_open_product UNIQUE (product_id, active_slot),
    CONSTRAINT ck_listings_open_slot CHECK (
        (status IN ('ACTIVE', 'RESERVED') AND active_slot IS NOT NULL AND active_slot = 1)
        OR (status IN ('SOLD', 'CANCELLED') AND active_slot IS NULL))
);
CREATE INDEX ix_listings_status_published ON listings(status, published_at, id);

CREATE TABLE listing_images (
    listing_id BIGINT NOT NULL REFERENCES listings(id),
    product_image_id BIGINT NOT NULL REFERENCES product_images(id),
    sort_order INTEGER NOT NULL CHECK (sort_order BETWEEN 0 AND 19),
    is_primary BOOLEAN NOT NULL,
    PRIMARY KEY (listing_id, product_image_id),
    CONSTRAINT uk_listing_images_order UNIQUE (listing_id, sort_order),
    CONSTRAINT ck_listing_images_primary CHECK (is_primary = (sort_order = 0))
);
