-- 증빙 사본(documents)과 AI 추출 시도(document_extractions).
-- 기준: 요구사항 정의서 v2.0 DOC-01~07, 임시 ERD(documents) + 승인된 document_extractions 분리
--
-- users, products, product_events를 가리키는 컬럼(product_id, uploader_id, requested_by_id,
-- result_event_id)은 선행 테이블이 머지되기 전에도 이 마이그레이션이 실행되도록 외래키 없이 정의한다.
-- 외래키는 선행 테이블이 머지된 뒤 별도 마이그레이션으로 추가한다.
-- 이력-증빙 연결 테이블(event_documents)은 이력 담당 범위라 이 마이그레이션에 포함하지 않는다.

CREATE TABLE documents (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id            BIGINT        NOT NULL,
    uploader_id           BIGINT        NOT NULL,
    object_key            VARCHAR(500)  NOT NULL,
    content_type          VARCHAR(100)  NOT NULL,
    byte_size             BIGINT        NOT NULL,
    version               INTEGER       NOT NULL DEFAULT 1,
    mask_confirmed_at     TIMESTAMP WITH TIME ZONE   NOT NULL,
    redaction_required_at TIMESTAMP WITH TIME ZONE,
    protected_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_documents_object_key UNIQUE (object_key),
    CONSTRAINT ck_documents_content_type CHECK (content_type IN ('image/jpeg', 'image/png', 'application/pdf')),
    CONSTRAINT ck_documents_byte_size CHECK (byte_size > 0 AND byte_size <= 10485760),
    CONSTRAINT ck_documents_version CHECK (version >= 1)
);

CREATE INDEX idx_documents_product ON documents (product_id, id);
CREATE INDEX idx_documents_uploader ON documents (uploader_id);

CREATE TABLE document_extractions (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id              BIGINT        NOT NULL REFERENCES documents (id),
    document_version         INTEGER       NOT NULL,
    requested_by_id          BIGINT        NOT NULL,
    consented_at             TIMESTAMP WITH TIME ZONE   NOT NULL,
    consent_notice_version   VARCHAR(30)   NOT NULL,
    status                   VARCHAR(30)   NOT NULL DEFAULT 'QUEUED',
    model_name               VARCHAR(100)  NOT NULL,
    schema_version           VARCHAR(30)   NOT NULL,
    extracted_facts          JSONB,
    error_code               VARCHAR(100),
    facts_confirmed_at       TIMESTAMP WITH TIME ZONE,
    result_event_id          BIGINT,
    created_at               TIMESTAMP WITH TIME ZONE   NOT NULL DEFAULT NOW(),
    updated_at               TIMESTAMP WITH TIME ZONE   NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_extractions_status CHECK (status IN ('QUEUED', 'PROCESSING', 'EXTRACTED', 'CONFIRMED', 'REJECTED', 'FAILED')),
    CONSTRAINT ck_extractions_confirmed CHECK (status <> 'CONFIRMED' OR facts_confirmed_at IS NOT NULL),
    CONSTRAINT ck_extractions_confirmed_at_only CHECK (facts_confirmed_at IS NULL OR status = 'CONFIRMED'),
    CONSTRAINT ck_extractions_result_event CHECK (result_event_id IS NULL OR status = 'CONFIRMED'),
    CONSTRAINT ck_extractions_facts_cleared CHECK (status <> 'CONFIRMED' OR extracted_facts IS NULL)
);

CREATE INDEX idx_extractions_document_created ON document_extractions (document_id, created_at);
CREATE INDEX idx_extractions_status_created ON document_extractions (status, created_at);
-- result_event_id는 NULL이 여러 개일 수 있으므로 일반 UNIQUE로 충분하다(NULL은 서로 다른 값으로 취급).
-- 하나의 이력이 최대 하나의 추출 결과에서만 만들어지도록 한다.
ALTER TABLE document_extractions
    ADD CONSTRAINT uk_extractions_result_event UNIQUE (result_event_id);

-- 문서당 동시에 유효한(QUEUED/PROCESSING/EXTRACTED/CONFIRMED) 추출은 하나만 허용해야 한다.
-- 이 규칙은 PostgreSQL 부분 UNIQUE 인덱스(WHERE status IN (...))가 필요하지만, 테스트가 H2로 모든 마이그레이션을
-- 실행하고 H2는 부분 인덱스를 지원하지 않아 이 마이그레이션에는 넣지 않았다.
-- 현재는 서비스가 문서 행을 잠근 뒤 활성 추출이 없을 때만 새 추출을 만든다.
-- 테스트 DB 방침(H2 / PostgreSQL)이 정해지면 PostgreSQL 전용 마이그레이션으로 인덱스를 추가한다.
