CREATE TABLE product_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    occurred_on DATE NOT NULL,
    title VARCHAR(200) NOT NULL,
    content TEXT,
    service_provider VARCHAR(100),
    replaced_part VARCHAR(100),
    reviewed BOOLEAN NOT NULL DEFAULT true,
    visibility VARCHAR(20) NOT NULL DEFAULT 'PRIVATE',
    status VARCHAR(20) NOT NULL DEFAULT 'VALID',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_product_events_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_product_events_author FOREIGN KEY (author_id) REFERENCES users(id)
);

CREATE INDEX ix_product_events_product_occurred ON product_events (product_id, occurred_on DESC, id DESC);

CREATE TABLE product_event_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    reason VARCHAR(500) NOT NULL,
    before_content TEXT,
    after_content TEXT,
    reviewed BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_product_event_corrections_event FOREIGN KEY (event_id) REFERENCES product_events(id) ON DELETE CASCADE,
    CONSTRAINT fk_product_event_corrections_actor FOREIGN KEY (actor_id) REFERENCES users(id)
);

CREATE INDEX ix_product_event_corrections_event ON product_event_corrections (event_id, created_at ASC);
