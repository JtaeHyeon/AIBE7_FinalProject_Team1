-- Shared product/user tables are owned by PROD/AUTH and do not exist in the baseline.
-- FK integration with those tables follows their migrations; ownership is checked under
-- the shared products row lock on every save. No listing or history state changes here.
CREATE TABLE listing_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL UNIQUE CHECK (product_id > 0),
    author_id BIGINT NOT NULL CHECK (author_id > 0),
    title VARCHAR(60),
    description VARCHAR(2000),
    price NUMERIC(12, 0) CHECK (price >= 1),
    condition_grade INTEGER CHECK (condition_grade BETWEEN 1 AND 5),
    visibility VARCHAR(20) NOT NULL DEFAULT 'PRIVATE' CHECK (visibility = 'PRIVATE'),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_listing_drafts_author ON listing_drafts(author_id, updated_at, id);

CREATE TABLE listing_draft_images (
    draft_id BIGINT NOT NULL REFERENCES listing_drafts(id) ON DELETE CASCADE,
    sort_order INTEGER NOT NULL CHECK (sort_order BETWEEN 0 AND 19),
    image_id BIGINT NOT NULL CHECK (image_id > 0),
    PRIMARY KEY (draft_id, sort_order)
);
