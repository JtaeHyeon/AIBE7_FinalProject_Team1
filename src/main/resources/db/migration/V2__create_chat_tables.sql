CREATE TABLE chat_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL,
    seller_id BIGINT NOT NULL,
    inquirer_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_chat_rooms_listing_inquirer UNIQUE (listing_id, inquirer_id),
    CONSTRAINT ck_chat_rooms_distinct_participants CHECK (seller_id <> inquirer_id)
);

CREATE INDEX ix_chat_rooms_seller_created ON chat_rooms (seller_id, created_at DESC);
CREATE INDEX ix_chat_rooms_inquirer_created ON chat_rooms (inquirer_id, created_at DESC);

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chat_messages_room FOREIGN KEY (room_id) REFERENCES chat_rooms (id),
    CONSTRAINT ck_chat_messages_content CHECK (CHAR_LENGTH(TRIM(content)) > 0)
);

CREATE INDEX ix_chat_messages_room_created ON chat_messages (room_id, created_at DESC, id DESC);

CREATE TABLE chat_read_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    last_read_message_id BIGINT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_chat_read_positions_room_user UNIQUE (room_id, user_id),
    CONSTRAINT fk_chat_read_positions_room FOREIGN KEY (room_id) REFERENCES chat_rooms (id),
    CONSTRAINT fk_chat_read_positions_message FOREIGN KEY (last_read_message_id) REFERENCES chat_messages (id)
);
