CREATE TABLE ownership_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    transfer_type VARCHAR(20) NOT NULL,
    purchase_request_id BIGINT,
    from_user_id BIGINT NOT NULL,
    to_user_id BIGINT,
    status VARCHAR(20) NOT NULL,
    token_hash VARCHAR(255),
    recipient_approved_at TIMESTAMP WITH TIME ZONE,
    owner_approved_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ownership_transfers_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_ownership_transfers_purchase_request FOREIGN KEY (purchase_request_id) REFERENCES purchase_requests (id),
    CONSTRAINT fk_ownership_transfers_from_user FOREIGN KEY (from_user_id) REFERENCES users (id),
    CONSTRAINT fk_ownership_transfers_to_user FOREIGN KEY (to_user_id) REFERENCES users (id),
    CONSTRAINT uk_ownership_transfers_purchase_request UNIQUE (purchase_request_id),
    CONSTRAINT uk_ownership_transfers_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_ownership_transfers_type CHECK (transfer_type IN ('INTERNAL', 'EXTERNAL')),
    CONSTRAINT ck_ownership_transfers_status CHECK (status IN ('PENDING', 'ACCEPTED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_ownership_transfers_distinct_users CHECK (to_user_id IS NULL OR from_user_id <> to_user_id),
    CONSTRAINT ck_ownership_transfers_shape CHECK (
        (transfer_type = 'INTERNAL'
            AND purchase_request_id IS NOT NULL
            AND to_user_id IS NOT NULL
            AND token_hash IS NULL
            AND recipient_approved_at IS NULL
            AND owner_approved_at IS NULL
            AND status <> 'EXPIRED')
        OR (transfer_type = 'EXTERNAL'
            AND purchase_request_id IS NULL
            AND token_hash IS NOT NULL)
    ),
    CONSTRAINT ck_ownership_transfers_approval CHECK (
        (recipient_approved_at IS NULL AND owner_approved_at IS NULL)
        OR (transfer_type = 'EXTERNAL'
            AND to_user_id IS NOT NULL
            AND recipient_approved_at IS NOT NULL)
    ),
    CONSTRAINT ck_ownership_transfers_external_acceptance CHECK (
        transfer_type <> 'EXTERNAL'
        OR status <> 'ACCEPTED'
        OR (to_user_id IS NOT NULL
            AND recipient_approved_at IS NOT NULL
            AND owner_approved_at IS NOT NULL)
    )
);
