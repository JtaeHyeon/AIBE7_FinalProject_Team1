UPDATE products
SET manufacturer_normalized = UPPER(REPLACE(REPLACE(TRIM(manufacturer), ' ', ''), '-', ''))
WHERE manufacturer_normalized IS NULL;

ALTER TABLE products ALTER COLUMN manufacturer_normalized SET NOT NULL;
ALTER TABLE products DROP CONSTRAINT IF EXISTS uk_products_serial_number_fingerprint;

ALTER TABLE products ADD CONSTRAINT uk_products_manufacturer_serial
    UNIQUE (manufacturer_normalized, serial_number_fingerprint);
ALTER TABLE products ADD CONSTRAINT ck_products_facts_version CHECK (facts_version >= 1);

CREATE TABLE product_field_authors (
    product_id BIGINT NOT NULL,
    field_name VARCHAR(40) NOT NULL,
    author_id BIGINT NOT NULL,
    PRIMARY KEY (product_id, field_name),
    CONSTRAINT fk_product_field_authors_product
        FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_product_field_authors_field CHECK (
        field_name IN ('TITLE', 'PURCHASE_DATE', 'WARRANTY_EXPIRES_AT', 'WARRANTY_TERMS')
    ),
    CONSTRAINT ck_product_field_authors_author CHECK (author_id > 0)
);

