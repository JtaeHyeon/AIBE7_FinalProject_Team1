CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    actor_id BIGINT,
    target_id BIGINT NOT NULL,
    before_facts TEXT,
    after_facts TEXT,
    reason VARCHAR(500),
    action VARCHAR(50) NOT NULL,
    result VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_logs_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_audit_logs_actor CHECK (actor_id IS NULL OR actor_id > 0),
    CONSTRAINT ck_audit_logs_result CHECK (result = 'SUCCESS')
);

CREATE INDEX ix_audit_logs_product_created
    ON audit_logs (product_id, created_at, id);
