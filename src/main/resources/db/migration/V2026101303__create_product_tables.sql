-- 제품(노트북) 테이블.
-- 공유 DB에는 products, laptop_details가 이미 적용되어 있어(V2~V4, 저장소에는 없음) IF NOT EXISTS로 건너뛴다.
-- 새 환경에서는 이 파일이 같은 구조의 테이블을 만든다. product_images는 새로 만든다.

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(30) NOT NULL,
    manufacturer VARCHAR(100) NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    purchase_date DATE,
    serial_number_fingerprint VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    title VARCHAR(200) NOT NULL,
    warranty_expires_at DATE,
    owner_id BIGINT NOT NULL,
    serial_number_ciphertext VARCHAR(512) NOT NULL,
    archived_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_products_category CHECK (category = 'LAPTOP'),
    CONSTRAINT ck_products_owner_id_required CHECK (owner_id > 0),
    CONSTRAINT uk_products_serial_number_fingerprint UNIQUE (serial_number_fingerprint)
);

CREATE TABLE IF NOT EXISTS laptop_details (
    product_id BIGINT PRIMARY KEY,
    cpu_spec VARCHAR(100),
    ram_gb INTEGER,
    storage_gb INTEGER,
    storage_type VARCHAR(20),
    gpu_spec VARCHAR(100),
    os_name VARCHAR(50),
    display_spec VARCHAR(100),
    battery_health_percent SMALLINT,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_laptop_details_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_laptop_details_memory_gb CHECK (ram_gb IS NULL OR ram_gb > 0),
    CONSTRAINT ck_laptop_details_storage_gb CHECK (storage_gb IS NULL OR storage_gb > 0),
    CONSTRAINT ck_laptop_details_storage_type
        CHECK (storage_type IS NULL OR storage_type IN ('SSD', 'HDD', 'MIXED')),
    CONSTRAINT ck_laptop_details_battery_health
        CHECK (battery_health_percent IS NULL
            OR (battery_health_percent >= 0 AND battery_health_percent <= 100))
);

CREATE TABLE IF NOT EXISTS product_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    storage_key VARCHAR(500) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_product_images_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_product_images_content_type
        CHECK (content_type IN ('image/png', 'image/jpeg', 'image/webp'))
);

CREATE INDEX IF NOT EXISTS ix_product_images_product ON product_images (product_id, sort_order, id);
